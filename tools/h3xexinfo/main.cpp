// h3xexinfo: inspect an Xbox 360 XEX and produce the bits of the XenonRecomp
// config that can be found mechanically.
//
//   h3xexinfo <xex> [--imports] [--stubs <out.cpp>]
//
// Always prints the image layout and scans code sections for the register
// save/restore helpers, printing ready-to-paste TOML lines. --imports lists
// every kernel/XAM import. --stubs writes weak stub definitions for every
// import so the runtime links before the real implementations exist.

#include <file.h>
#include <image.h>

#include <cstdio>
#include <cstring>
#include <fstream>
#include <string>
#include <string_view>
#include <vector>

namespace
{
    struct HelperPattern
    {
        const char* key;
        std::vector<uint8_t> bytes;
    };

    // Byte patterns from XenonRecomp's README.
    const HelperPattern kHelperPatterns[] =
    {
        { "restgprlr_14_address", { 0xE9, 0xC1, 0xFF, 0x68 } },
        { "savegprlr_14_address", { 0xF9, 0xC1, 0xFF, 0x68 } },
        { "restfpr_14_address",   { 0xC9, 0xCC, 0xFF, 0x70 } },
        { "savefpr_14_address",   { 0xD9, 0xCC, 0xFF, 0x70 } },
        { "restvmx_14_address",   { 0x39, 0x60, 0xFE, 0xE0, 0x7D, 0xCB, 0x60, 0xCE } },
        { "savevmx_14_address",   { 0x39, 0x60, 0xFE, 0xE0, 0x7D, 0xCB, 0x61, 0xCE } },
        { "restvmx_64_address",   { 0x39, 0x60, 0xFC, 0x00, 0x10, 0x0B, 0x60, 0xCB } },
        { "savevmx_64_address",   { 0x39, 0x60, 0xFC, 0x00, 0x10, 0x0B, 0x61, 0xCB } },
    };

    constexpr std::string_view kImportPrefix = "__imp__";

    std::vector<size_t> FindPattern(const Image& image, const std::vector<uint8_t>& pattern)
    {
        std::vector<size_t> matches;
        for (const auto& section : image.sections)
        {
            if ((section.flags & SectionFlags_Code) == 0 || section.size < pattern.size())
                continue;

            // PPC instructions are 4-byte aligned.
            for (size_t offset = 0; offset + pattern.size() <= section.size; offset += 4)
            {
                if (memcmp(section.data + offset, pattern.data(), pattern.size()) == 0)
                    matches.push_back(section.base + offset);
            }
        }
        return matches;
    }

    std::vector<const Symbol*> CollectImports(const Image& image)
    {
        std::vector<const Symbol*> imports;
        for (const auto& symbol : image.symbols)
        {
            if (std::string_view(symbol.name).starts_with(kImportPrefix))
                imports.push_back(&symbol);
        }
        return imports;
    }

    bool WriteStubs(const std::vector<const Symbol*>& imports, const char* path)
    {
        std::ofstream out(path);
        if (!out)
            return false;

        out << "// Generated by h3xexinfo. Do not edit; implement imports in H3Recomp/kernel/ instead.\n"
               "// Strong definitions there override these weak fallbacks.\n\n"
               "#include \"ppc_recomp_shared.h\"\n"
               "#include <kernel/imports.h>\n\n";

        for (const Symbol* symbol : imports)
        {
            std::string_view name = std::string_view(symbol->name).substr(kImportPrefix.size());
            out << "PPC_WEAK_FUNC(" << symbol->name << ") { h3::kernel::UnimplementedImport(\""
                << name << "\", ctx); }\n";
        }
        return true;
    }
}

int main(int argc, char* argv[])
{
    if (argc < 2)
    {
        fprintf(stderr, "Usage: h3xexinfo <xex> [--imports] [--stubs <out.cpp>]\n");
        return 1;
    }

    const char* xexPath = argv[1];
    bool listImports = false;
    const char* stubsPath = nullptr;

    for (int i = 2; i < argc; i++)
    {
        if (strcmp(argv[i], "--imports") == 0)
            listImports = true;
        else if (strcmp(argv[i], "--stubs") == 0 && i + 1 < argc)
            stubsPath = argv[++i];
        else
        {
            fprintf(stderr, "Unknown argument: %s\n", argv[i]);
            return 1;
        }
    }

    std::vector<uint8_t> file = LoadFile(xexPath);
    if (file.empty())
    {
        fprintf(stderr, "Failed to read %s\n", xexPath);
        return 1;
    }

    Image image = Image::ParseImage(file.data(), file.size());
    if (image.data == nullptr)
    {
        fprintf(stderr, "Failed to parse %s as an XEX (encrypted with an unsupported key?)\n", xexPath);
        return 1;
    }

    printf("Image base:  0x%08zX\n", image.base);
    printf("Image size:  0x%08X\n", image.size);
    printf("Entry point: 0x%08zX\n\n", image.entry_point);

    printf("Sections:\n");
    for (const auto& section : image.sections)
    {
        printf("  %-10s 0x%08zX - 0x%08zX  %s%s\n", section.name.c_str(), section.base,
            section.base + section.size,
            (section.flags & SectionFlags_Code) ? "code " : "",
            (section.flags & SectionFlags_Data) ? "data" : "");
    }

    std::vector<const Symbol*> imports = CollectImports(image);
    printf("\nImports: %zu (use --imports to list)\n", imports.size());
    if (listImports)
    {
        for (const Symbol* symbol : imports)
            printf("  0x%08zX  %s\n", symbol->address, symbol->name.c_str() + kImportPrefix.size());
    }

    printf("\n# Paste into H3RecompLib/config/halo3.toml [main]:\n");
    for (const auto& helper : kHelperPatterns)
    {
        std::vector<size_t> matches = FindPattern(image, helper.bytes);
        if (matches.size() == 1)
        {
            printf("%s = 0x%08zX\n", helper.key, matches[0]);
        }
        else
        {
            printf("# %s: %zu matches, check in Ghidra:", helper.key, matches.size());
            for (size_t match : matches)
                printf(" 0x%08zX", match);
            printf("\n");
        }
    }

    if (stubsPath != nullptr)
    {
        if (!WriteStubs(imports, stubsPath))
        {
            fprintf(stderr, "Failed to write %s\n", stubsPath);
            return 1;
        }
        printf("\nWrote %zu import stubs to %s\n", imports.size(), stubsPath);
    }

    return 0;
}
